import { expect, test } from "@playwright/test";
import ExcelJS from "exceljs";
import { mkdir } from "node:fs/promises";
import path from "node:path";

test("a new fleet can log, sign, export, and return without external APIs", async ({ page, request }) => {
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  // The offline manual-entry journey must not depend on map/weather services.
  await page.route(/^https?:\/\/(?!localhost:3123|127\.0\.0\.1:3123)/, (route) => route.abort());
  expect((await request.get("/api/export/pdf?aircraft=missing")).status()).toBe(401);
  expect((await request.post("/api/import")).status()).toBe(401);
  await page.goto("/flights");
  await expect(page).toHaveURL(/\/sign-in/);
  await page.goto("/sign-up");
  const email = `sample-${Date.now()}@example.com`;
  await page.getByLabel(/Full name/).fill("Sample Pilot / 架空の操縦者");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel(/Password/).fill("fictional-test-password-2026");
  const invite = page.getByLabel("Invite code");
  if (await invite.isVisible()) await invite.fill("fictional-e2e-fleet");
  await page.getByRole("button", { name: "Create account" }).click();
  await page.waitForURL((url) => !url.pathname.startsWith("/sign-up"));
  await page.goto("/aircraft");
  await page.getByRole("button", { name: "Add aircraft" }).first().click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel(/^Name/).fill("Demo aircraft");
  await dialog.getByLabel(/^Model/).fill("Fictional aircraft");
  await dialog.getByLabel(/Registration ID/).fill("SAMPLE-NOT-REGISTERED");
  await dialog.getByLabel(/^DJI serial/).fill("FICTIONAL-SERIAL-001");
  await dialog.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Aircraft added", { exact: true })).toBeVisible();
  await page.goto("/flights/new");
  await page.getByLabel("Date", { exact: true }).fill("2026-10-20");
  await page.getByLabel("Takeoff", { exact: true }).fill("09:12");
  await page.getByRole("button", { name: "20 min", exact: true }).click();
  await page.getByLabel("Takeoff place", { exact: true }).fill("架空の飛行場 / Fictional flying field");
  await page.getByRole("button", { name: "Training", exact: true }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.waitForURL(/\/flights\/[0-9a-f-]{36}$/);
  const flightUrl = page.url();
  await page.goto("/settings");
  const pad = await page.getByLabel("Signature pad").boundingBox();
  expect(pad).not.toBeNull();
  await page.mouse.move(pad!.x + 30, pad!.y + 80);
  await page.mouse.down();
  for (let i = 0; i < 20; i++) await page.mouse.move(pad!.x + 35 + i * 12, pad!.y + 80 + Math.sin(i) * 18, { steps: 2 });
  await page.mouse.up();
  await page.getByRole("button", { name: "Save signature" }).click();
  await expect(page.getByText("Signature saved", { exact: true })).toBeVisible();
  await page.goto(flightUrl);
  await page.getByRole("button", { name: "Review & sign", exact: true }).first().click();
  await page.getByRole("button", { name: "Sign", exact: true }).click();
  await expect(page.getByText("Flight signed", { exact: true })).toBeVisible();
  await page.goto("/log");
  await expect(page.getByText("JOURNEY LOG OF UAS", { exact: true }).first()).toBeVisible();
  const pdfHref = await page.getByRole("link", { name: /PDF logbook/ }).getAttribute("href");
  const pdf = await page.request.get(pdfHref!);
  expect(pdf.status()).toBe(200);
  expect((await pdf.body()).subarray(0, 5).toString()).toBe("%PDF-");
  const xlsxHref = await page.getByRole("link", { name: /Excel/ }).getAttribute("href");
  const xlsx = await page.request.get(xlsxHref!);
  expect(xlsx.status()).toBe(200);
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(await xlsx.body() as unknown as ArrayBuffer);
  expect(workbook.worksheets[0].getCell("D5").text).toContain("Sample Pilot");
  expect(workbook.worksheets[0].getCell("L5").text).toBe("09:12");
  expect(workbook.worksheets[0].getImages()).toHaveLength(1);
  if (process.env.E2E_SHOTS) {
    await mkdir(process.env.E2E_SHOTS, { recursive: true });
    await page.screenshot({ path: path.join(process.env.E2E_SHOTS, "app-logbook.png"), fullPage: true });
    await page.goto(flightUrl);
    await page.screenshot({ path: path.join(process.env.E2E_SHOTS, "app-flight.png"), fullPage: true });
  }
  // Malformed uploads fail without becoming flights.
  const bad = await page.request.post("/api/import", { multipart: { file: { name: "invalid.txt", mimeType: "text/plain", buffer: Buffer.from("synthetic invalid input") } } });
  expect(bad.status()).toBe(422);
  await page.context().clearCookies();
  await page.goto("/flights");
  await expect(page).toHaveURL(/\/sign-in/);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill("fictional-test-password-2026");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/flights$/);
  await expect(page.getByRole("cell", { name: "SAMPLE-NOT-REGISTERED", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "Signed", exact: true })).toBeVisible();
  expect(failures).toEqual([]);
});
